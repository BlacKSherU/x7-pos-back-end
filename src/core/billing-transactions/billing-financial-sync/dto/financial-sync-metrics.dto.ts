import { ApiProperty } from '@nestjs/swagger';
import { SuccessResponse } from 'src/common/dtos/success-response.dto';
import { AccountType } from 'src/core/financial-engine/ledger-accounts/constants/account-type.enum';
import { JournalEntryStatus } from 'src/core/financial-engine/journal-entry/constants/journal-entry-status.enum';

import type { PostingSkipReason } from '../billing-financial-sync.calculations';

export type LedgerBalanceStatus = 'BALANCED' | 'UNBALANCED' | 'NO_ENTRIES';

export class FinancialSyncTaxAccountDto {
  @ApiProperty({ example: 4 })
  account_id: number;

  @ApiProperty({ example: '2100' })
  code: string;

  @ApiProperty({ example: 'VAT payable' })
  name: string;

  @ApiProperty({
    example: 128.4,
    description: 'Credit − debit over POSTED entries of the company',
  })
  balance: number;
}

export class FinancialSyncBalanceStatusDto {
  @ApiProperty({ enum: ['BALANCED', 'UNBALANCED', 'NO_ENTRIES'] })
  status: LedgerBalanceStatus;

  @ApiProperty({
    example: 40,
    description: 'Receipts with live journal entries',
  })
  checked_receipts: number;

  @ApiProperty({ example: 39 })
  balanced_receipts: number;

  @ApiProperty({ example: 1 })
  unbalanced_receipts: number;
}

export class FinancialSyncMetricsDto {
  @ApiProperty({ example: 'USD', description: 'Company base currency' })
  currency: string;

  @ApiProperty({ example: 52, description: 'Active receipts of the merchant' })
  total_receipts: number;

  @ApiProperty({
    example: 40,
    description: 'Receipts whose entries are all posted',
  })
  posted_receipts: number;

  @ApiProperty({ example: 2, description: 'Receipts with DRAFT entries' })
  pending_receipts: number;

  @ApiProperty({ example: 10, description: 'Receipts without live entries' })
  unposted_receipts: number;

  @ApiProperty({
    example: 12,
    description: 'Receipts not fully posted (unposted + pending)',
  })
  unposted_transactions: number;

  @ApiProperty({
    example: 3,
    description: 'DRAFT journal entries linked to receipts',
  })
  pending_ledger_entries: number;

  @ApiProperty({
    example: 41,
    description: 'POSTED entries linked to receipts',
  })
  posted_ledger_entries: number;

  @ApiProperty({
    example: 1840.5,
    description: 'Net credit on REVENUE accounts of POSTED receipt entries',
  })
  posted_revenue: number;

  @ApiProperty({
    example: 2150.75,
    description: 'Σ grand_total of the posted receipts',
  })
  posted_grand_total: number;

  @ApiProperty({ type: () => [FinancialSyncTaxAccountDto] })
  tax_accounts: FinancialSyncTaxAccountDto[];

  @ApiProperty({ example: 310.25, description: 'Σ balances of tax_accounts' })
  tax_liability_balance: number;

  @ApiProperty({ type: () => FinancialSyncBalanceStatusDto })
  balance: FinancialSyncBalanceStatusDto;
}

export class OneFinancialSyncMetricsResponse extends SuccessResponse {
  @ApiProperty({ type: () => FinancialSyncMetricsDto })
  data: FinancialSyncMetricsDto;
}

export class FinancialSyncPostingAccountDto {
  @ApiProperty({ example: 1 })
  id: number;

  @ApiProperty({ example: '1100' })
  code: string;

  @ApiProperty({ example: 'Cash on hand' })
  name: string;

  @ApiProperty({ enum: AccountType, example: AccountType.ASSET })
  type: AccountType;
}

export class FinancialSyncPostingAccountsResponse extends SuccessResponse {
  @ApiProperty({ type: () => [FinancialSyncPostingAccountDto] })
  data: FinancialSyncPostingAccountDto[];
}

export class PostedReceiptEntryDto {
  @ApiProperty({ example: 120 })
  id: number;

  @ApiProperty({ example: 'RCPT-INV-000010' })
  entry_number: string;

  @ApiProperty({ example: 10 })
  receipt_id: number;

  @ApiProperty({ enum: JournalEntryStatus, example: JournalEntryStatus.POSTED })
  status: JournalEntryStatus;

  @ApiProperty({ example: 29.28 })
  total_debit: number;

  @ApiProperty({ example: 29.28 })
  total_credit: number;

  @ApiProperty({
    example: true,
    description:
      'true: generated by this batch · false: existing DRAFT entry posted',
  })
  generated: boolean;
}

export class SkippedReceiptDto {
  @ApiProperty({ example: 11 })
  receipt_id: number;

  @ApiProperty({ example: 'INV-000011', nullable: true, type: String })
  invoice_number: string | null;

  @ApiProperty({
    enum: [
      'NOT_FOUND',
      'ALREADY_POSTED',
      'UNBALANCED_DRAFT',
      'ZERO_AMOUNT',
      'NEGATIVE_AMOUNTS',
      'UNBALANCED_TOTALS',
      'MISSING_TAX_ACCOUNT',
      'MISSING_DISCOUNT_ACCOUNT',
    ],
  })
  reason: PostingSkipReason;

  @ApiProperty({
    example:
      'Receipt INV-000011 carries tax but no tax liability account was selected',
  })
  detail: string;
}

export class PostBatchResultDto {
  @ApiProperty({
    example: 8,
    description: 'Journal entries generated and posted',
  })
  generated_entries: number;

  @ApiProperty({ example: 1, description: 'Existing DRAFT entries posted' })
  posted_drafts: number;

  @ApiProperty({ type: () => [PostedReceiptEntryDto] })
  entries: PostedReceiptEntryDto[];

  @ApiProperty({ type: () => [SkippedReceiptDto] })
  skipped: SkippedReceiptDto[];

  @ApiProperty({
    type: () => FinancialSyncMetricsDto,
    description:
      'Header metrics after the batch, to refresh the counters at once',
  })
  metrics: FinancialSyncMetricsDto;
}

export class PostBatchToLedgerResponse extends SuccessResponse {
  @ApiProperty({ type: () => PostBatchResultDto })
  data: PostBatchResultDto;
}
